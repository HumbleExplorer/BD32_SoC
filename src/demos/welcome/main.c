/* CLINT 汇编接口 */
extern void clint_asm_set_timeout_ticks(uint32_t ticks);

/* APB Timer 外设寄存器 */
#define PTIMER_BASE  0xE0020000UL
#define PTIM_PSC     (*(volatile uint32_t*)(PTIMER_BASE + 0x00))
#define PTIM_CNT     (*(volatile uint32_t*)(PTIMER_BASE + 0x04))
#define PTIM_ARR     (*(volatile uint32_t*)(PTIMER_BASE + 0x08))
#define PTIM_CR      (*(volatile uint32_t*)(PTIMER_BASE + 0x0C))
#define PTIM_SR      (*(volatile uint32_t*)(PTIMER_BASE + 0x14))

#define BREATH_STEPS  128         /* 128 步 → ~1.3s 半周期 */
#define CLINT_PERIOD  25000000    /* 250ms @ 100MHz → 2Hz toggle */

