/* ================================================================
 * CLINT 中断处理 — GPIO[3] 翻转
 *
 * 注意：ISR 直接写 GPIO_OUT，不经过 RMW，避免与主循环竞争
 * ================================================================ */
static volatile uint32_t gpio_shadow;  /* 主循环+ISR 共用的 GPIO 镜像 */

void tmr_irq_handler(void) {
    gpio_shadow ^= PIN_LED0;
    GPIO_OUT = gpio_shadow;
    clint_asm_set_timeout_ticks(CLINT_PERIOD);
}

/* ================================================================
 * 关/开中断 — 保护主循环中 GPIO_OUT 的 RMW 操作
 * ================================================================ */
static inline uint32_t intr_disable(void) {
    uint32_t mstatus;
    __asm__ volatile("csrrci %0, mstatus, 0x8" : "=r"(mstatus));
    return mstatus;
}
static inline void intr_restore(uint32_t mstatus) {
    __asm__ volatile("csrw mstatus, %0" : : "r"(mstatus));
}

/* ================================================================
 * 主函数
 * ================================================================ */
int main(void) {
    uart_init();

    /* ===== 1. 打印 Logo ===== */
    uart_puts(logo);
    uart_puts("              ");
    print_cn();
    uart_puts("\n              Welcome to use the Blue Dream Processor!\n\n");

    /* ===== 2. 配置 GPIO ===== */
    GPIO_DIR |= (PIN_LED0 | PIN_LED1);
    gpio_shadow = 0;
    GPIO_OUT = 0;  /* 两灯初始灭 */

    /* ===== 3. 配置 APB Timer ===== */
    /* PSC=199, ARR=249 → 500KHz tick, 250 tick 周期 = 0.5ms/step */
    /* 128 步 → 64ms 半周期 → ~128ms 完整呼吸 */
    PTIM_PSC = 199;
    PTIM_ARR  = 249;
    PTIM_CR   = 1;

    /* ===== 4. 配置 CLINT 中断 ===== */
    clint_asm_set_timeout_ticks(CLINT_PERIOD);

    /* ===== 5. 开中断 ===== */
    __asm__ volatile(
        "li t0, 0x80\n"
        "csrs mie, t0\n"
        "li t0, 0x1888\n"
        "csrw mstatus, t0\n"
        : : : "t0"
    );

    /* ===== 6. PWM 呼吸灯 + GPIO[3] 闪烁 ===== */
    uint32_t duty = 0;
    int dir = 1;
    uint32_t pwm_cnt = 0;

    while (1) {
        /* 等待 APB Timer 溢出 */
        while (!(PTIM_SR & 1));
        PTIM_SR = 1;

        pwm_cnt++;
        if (pwm_cnt >= BREATH_STEPS) {
            pwm_cnt = 0;
            if (dir > 0) {
                if (duty >= BREATH_STEPS - 1) { dir = -1; duty--; }
                else duty++;
            } else {
                if (duty == 0) { dir = 1; duty++; }
                else duty--;
            }
        }

        /* 关中断保护 GPIO[4] 的 RMW 操作 */
        uint32_t ms = intr_disable();
        if (pwm_cnt < duty)
            gpio_shadow |= PIN_LED1;
        else
            gpio_shadow &= ~PIN_LED1;
        GPIO_OUT = gpio_shadow;
        intr_restore(ms);
    }
}
