# Generate crc32_test.S: init CRC table (256 entries) into DTCM at 0x1A000 via sw,
# init buffer "123456789" at 0x1B000, run coremark-style crc32, compare to 0xCBF43926.
def gen_table():
    t = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (0xEDB88320 ^ (c >> 1)) if (c & 1) else (c >> 1)
        t.append(c & 0xFFFFFFFF)
    return t

table = gen_table()
def crc32(buf):
    crc = 0xFFFFFFFF
    for b in buf:
        crc = table[(crc ^ b) & 0xFF] ^ (crc >> 8)
    return (~crc) & 0xFFFFFFFF
assert crc32(b"123456789") == 0xCBF43926, hex(crc32(b"123456789"))

L = []
L.append("# crc32_test.S - coremark-style CRC32 table lookup (common path for all 3 CRCs).")
L.append("# Table init via sw to DTCM@0x1A000 (CORE_TEST .data not auto-loaded).")
L.append("# Buffer '123456789' @0x1B000. Expected CRC32 = 0xCBF43926.")
L.append("")
L.append('#include "riscv_test.h"')
L.append("#undef RVTEST_RV64U")
L.append("#define RVTEST_RV64U RVTEST_RV32U")
L.append("")
L.append("  RVTEST_CODE_BEGIN")
L.append("")
L.append("  # ---- init CRC table at 0x1A000 ----")
L.append("  li x2, 0x1A000")
L.append("  li x3, 0")
L.append("tbl_init_loop:")
L.append("  li x4, 256")
L.append("  bge x3, x4, tbl_init_done")
L.append("  mv x5, x3            # c = i")
L.append("  li x6, 0             # j = 0")
L.append("tbl_bit_loop:")
L.append("  li x7, 8")
L.append("  bge x6, x7, tbl_bit_done")
L.append("  andi x8, x5, 1       # c & 1")
L.append("  beq x8, x0, tbl_shr")
L.append("  lui x11, 0xEDB88")
L.append("  addi x11, x11, 0x320  # x11 = 0xEDB88320")
L.append("  srli x9, x5, 1")
L.append("  xor x5, x11, x9       # c = 0xEDB88320 ^ (c>>1)")
L.append("  j tbl_bit_next")
L.append("tbl_shr:")
L.append("  srli x5, x5, 1        # c = c>>1")
L.append("tbl_bit_next:")
L.append("  addi x6, x6, 1")
L.append("  j tbl_bit_loop")
L.append("tbl_bit_done:")
L.append("  slli x12, x3, 2       # i*4")
L.append("  add x13, x2, x12      # &table[i]")
L.append("  sw x5, 0(x13)         # table[i] = c")
L.append("  addi x3, x3, 1")
L.append("  j tbl_init_loop")
L.append("tbl_init_done:")
L.append("  # ---- init buffer at 0x1B000: '123456789' ----")
buf = b"123456789"
L.append("  li x14, 0x1B000")
for i, ch in enumerate(buf):
    L.append("  li x15, %d" % ch)
    L.append("  sb x15, %d(x14)" % i)
L.append("")
L.append("  # ---- crc32 over buffer (9 bytes) ----")
L.append("  li x16, 0x1B000      # buf ptr")
L.append("  li x17, 9            # len")
L.append("  li x18, 0xFFFFFFFF   # crc = ~0")
L.append("crc_loop:")
L.append("  beq x17, x0, crc_done")
L.append("  lbu x19, 0(x16)      # b = buf[i]")
L.append("  xor x20, x18, x19    # crc ^ b")
L.append("  andi x20, x20, 0xFF  # & 0xff -> index")
L.append("  slli x21, x20, 2     # index*4")
L.append("  add x22, x2, x21     # &table[index]")
L.append("  lw x23, 0(x22)       # table[index]  <-- CRC TABLE LOOKUP")
L.append("  srli x24, x18, 8     # crc >> 8")
L.append("  xor x18, x23, x24    # crc = table[index] ^ (crc>>8)")
L.append("  addi x16, x16, 1")
L.append("  addi x17, x17, -1")
L.append("  j crc_loop")
L.append("crc_done:")
L.append("  not x18, x18         # crc = ~crc")
L.append("  li x25, 0xCBF43926")
L.append("  bne x18, x25, failCRC")
L.append("")
L.append("  li x26, 1")
L.append("  li x27, 1")
L.append("pass_loop:")
L.append("  j pass_loop")
L.append("failCRC:")
L.append("  li x26, 1")
L.append("  li x27, 0")
L.append("  li gp, 40")
L.append("fail_loop:")
L.append("  j fail_loop")
L.append("")
L.append("  RVTEST_CODE_END")
L.append("  RVTEST_DATA_BEGIN")
L.append("  RVTEST_DATA_END")

with open("crc32_test.S", "w") as f:
    f.write("\n".join(L) + "\n")
