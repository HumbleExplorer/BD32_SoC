#!/usr/bin/env python
"""xpr_normalize.py — Vivado 工程文件(.xpr)重序列化噪声规范化器（防 churn 复发）

背景（2026-09-20 .xpr churn 收拢，见 Memory_Log 与 CHANGELOG）：
Vivado 每次打开/保存工程都会把 impl 段的 <ReportConfig> 报告自动配置整段展开
重序列化写回（本次实例 130 行：ReportConfig/ReportConfigOption/dummy_option
等默认值），功能上无意义但持续污染 git diff。本工具把 .xpr 收敛到确定的
紧凑形态，配合 pre-commit 钩子保证提交内容稳定可读。

规范化动作（幂等：normalize(normalize(x)) == normalize(x)）：
  1. 删除所有 <ReportConfig ...>...</ReportConfig> 块（含 ReportConfigOption /
     ReportConfigOutputOption 子行与自闭合形态）。删除后 Vivado 下次打开按
     流程默认行为生成报告，不影响综合/实现/比特流；自动报告 .rpt 在下次
     Vivado 保存前可能少几个，无害。
  2. 空展开元素 <X ...>\n</X> 折回自闭合 <X .../>（块删除后 ReportStrategy
     等变空的形态）。
  3. 连续多空行折叠为单空行。
  不做：选项行排序（Strategy 内 <Option> 行位置漂移是 Vivado 行为，最多
     几行 diff，接受）；CtrlBit 等属性不动（Vivado 生成的稳定元数据）。

用法：
  python SDK/tools/xpr_normalize.py [path]          # 原地规范化（默认 BD32_SoC/BD32_SoC.xpr）
  python SDK/tools/xpr_normalize.py --check [path]  # 只检查：已规范化 exit 0，否则 exit 1
  python SDK/tools/xpr_normalize.py --install-hook  # 安装/刷新 .git/hooks/pre-commit
                                                     # （提交前自动规范化 staged .xpr）
"""
import argparse
import os
import re
import sys

HOOK_MARKER = "# BD32 xpr-normalize (auto-generated by SDK/tools/xpr_normalize.py)"
HOOK_BODY = """#!/bin/sh
{marker}
# 提交前把 staged 的 *.xpr 规范化（剥离 Vivado 重序列化噪声），保持 .xpr diff 干净。
# 手动禁用：删除本钩子或把本标记行注释掉。
files=$(git diff --cached --name-only | grep '\\.xpr$' || true)
[ -z "$files" ] && exit 0
for f in $files; do
  if ! python SDK/tools/xpr_normalize.py --check "$f" >/dev/null 2>&1; then
    python SDK/tools/xpr_normalize.py "$f" || exit 1
    git add "$f" || exit 1
    echo "[pre-commit] xpr-normalize: $f"
  fi
done
exit 0
""".format(marker=HOOK_MARKER)


def default_xpr():
    # SDK/tools/xpr_normalize.py → Working/
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    return os.path.join(root, "BD32_SoC", "BD32_SoC.xpr")


def repo_root():
    return os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def resolve_within_repo(path):
    """路径安全校验：规范化后必须落在仓库根子树内，拒绝 ../ 逃逸（与
    uart_send.py::safe_log_path 同约定）。返回规范化后的绝对路径。"""
    root = os.path.realpath(repo_root())
    target = os.path.realpath(path)
    if target == root or target.startswith(root + os.sep):
        return target
    print(f"[ERROR] 路径越出仓库目录 {root}：{path}")
    sys.exit(1)


def strip_report_config_blocks(lines):
    """逐行状态机：整块删除 <ReportConfig>...</ReportConfig>（含子行）与自闭合行。"""
    out = []
    depth = 0
    for line in lines:
        s = line.strip()
        if depth:
            if s.startswith("</ReportConfig>"):
                depth -= 1
            continue
        if s.startswith("<ReportConfig"):
            if s.endswith("/>"):
                continue
            depth += 1
            continue
        out.append(line)
    return out


def collapse_empty_elements(text):
    """<X attrs>\n[仅空行]</X> → <X attrs/>（行扫描，绝不跨名/跨子元素）。
    仅当：开标签行以 '>' 结束且非自闭合；向前找到**同名**闭合行 '</X>'；
    其间所有行都是空行。任何一条不满足就原样保留，避免把 '<Gadget' 误折到
    '</Gadget>'（正则前缀回溯的坑）。"""
    lines = text.split("\n")
    out = []
    i = 0
    n = len(lines)
    open_re = re.compile(r"^([ \t]*<([A-Za-z_][\w.]*)([^>]*?))\s*>$")
    while i < n:
        raw = lines[i]
        s = raw.strip()
        m = open_re.match(raw)
        is_open = bool(m) and not s.endswith("/>") and not s.startswith("</")
        if is_open:
            name = m.group(2)
            close = "</%s>" % name
            j = i + 1
            found = False
            while j < n:
                st = lines[j].strip()
                if st == close:
                    if all(lines[k].strip() == "" for k in range(i + 1, j)):
                        base = raw.rstrip()
                        out.append(base[:-1] + "/>")  # 去掉末尾 '>' 再补 '/>'
                        i = j + 1
                        found = True
                    break
                elif st == "":
                    j += 1
                else:
                    break
            if found:
                continue
        out.append(raw)
        i += 1
    return "\n".join(out)


def normalize_text(text):
    text = "\n".join(strip_report_config_blocks(text.split("\n")))
    text = collapse_empty_elements(text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    text = text.rstrip("\n") + "\n"
    return text


def install_hook(git_dir):
    hook = os.path.join(git_dir, "hooks", "pre-commit")
    body = HOOK_BODY
    if os.path.exists(hook):
        with open(hook, encoding="utf-8") as f:
            old = f.read()
        if HOOK_MARKER in old:
            # 已有我们的钩子：刷新到最新模板
            with open(hook, "w", encoding="utf-8", newline="\n") as f:
                f.write(body)
            print(f"[OK] pre-commit 钩子已刷新: {hook}")
            return
        print(f"[ERROR] 已存在非 xpr-normalize 的 pre-commit 钩子，拒绝覆盖：{hook}")
        print("请手工把下方内容并入现有钩子：")
        print(body)
        sys.exit(1)
    os.makedirs(os.path.dirname(hook), exist_ok=True)
    with open(hook, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    os.chmod(hook, 0o755)
    print(f"[OK] pre-commit 钩子已安装: {hook}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("path", nargs="?", default=None,
                   help="目标 .xpr（默认 BD32_SoC/BD32_SoC.xpr）")
    ap.add_argument("--check", action="store_true",
                    help="只检查是否已规范化（未规范化 exit 1），不写盘")
    ap.add_argument("--install-hook", action="store_true",
                    help="安装/刷新 .git/hooks/pre-commit（提交前自动规范化 staged .xpr）")
    args = ap.parse_args()

    if args.install_hook:
        # 定位 git 根（Working/）：从脚本位置向上找 .git；并校验它确实是本脚本
        # 所在仓库根（防止钩子被写到别处）
        d = os.path.dirname(os.path.abspath(__file__))
        git_root = None
        while d:
            if os.path.isdir(os.path.join(d, ".git")):
                git_root = d
                break
            d = os.path.dirname(d)
        if not git_root:
            print("[ERROR] 未找到 git 仓库根")
            sys.exit(1)
        if os.path.realpath(git_root) != os.path.realpath(repo_root()):
            print(f"[ERROR] git 根 {git_root} 与脚本所在仓库根 {repo_root()} 不一致，拒绝安装")
            sys.exit(1)
        install_hook(git_root)
        return

    path = args.path or default_xpr()
    path = resolve_within_repo(path)
    if not os.path.exists(path):
        print(f"[ERROR] 文件不存在: {path}")
        sys.exit(1)
    with open(path, encoding="utf-8") as f:
        text = f.read()
    norm = normalize_text(text)
    if norm == text:
        print(f"[OK] 已规范化: {path}")
        return
    delta_removed = text.count("\n") - norm.count("\n")
    if args.check:
        print(f"[DRY-RUN] 未规范化: {path}（规范化将减少约 {max(delta_removed, 0)} 行噪声）",
              file=sys.stderr)
        sys.exit(1)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(norm)
    print(f"[OK] 已规范化: {path}（删除约 {max(delta_removed, 0)} 行 Vivado 重序列化噪声）")


if __name__ == "__main__":
    main()
