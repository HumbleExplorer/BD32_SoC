#!/usr/bin/env python3
"""BD32 BootROM (MROM) 一键更新——校验/生成器（纯文件变换，零进程调用）

两个已固化的构建约束：
  A: 只 as 不 ld —— `call` 的 auipc+jalr 重定位需要链接器解析，
     跳过 ld 会留下 delta=0 的自跳转死循环。构建必须走完整链接（见 bat）。
  B: mrom BRAM IP 读的是 mrom.coe（不是 mrom.dat），且 Vivado 感知不到
     COE 内容变化，必须 reset_target+generate_target+重跑 mrom_synth_1
     （生成 synth_flow_mrom_coe.tcl，见 --emit-tcl）。

标准流程（三步）:
  1) SDK/tools/update_mrom_build.bat     # 链接 mrom.s → mrom.elf（含未解析跳转检查）
  2) python SDK/tools/update_mrom.py     # 解析 ELF → 校验 → 生成 mrom.dat + mrom.coe
  3) SDK/tools/update_mrom_synth.bat     # IP 刷新 + 综合 + 比特流（约 40 分钟）

bat 可随时用 --emit-bat 重新生成；本脚本自身不调用任何外部进程：
ELF 解析在 python 内完成，工具调用全部封装在 bat 里。
"""
import argparse
import os
import struct
import sys

_TOOLS = os.path.dirname(os.path.abspath(__file__))
_SDK = os.path.dirname(_TOOLS)
REPO_ROOT = os.path.realpath(os.path.dirname(_SDK))
ELF_PATH = os.path.realpath(os.path.join(REPO_ROOT, "test_data", "soc", "mrom_build", "mrom.elf"))
MROM_DAT = os.path.realpath(os.path.join(REPO_ROOT, "test_data", "soc", "mrom.dat"))
MROM_COE = os.path.realpath(os.path.join(REPO_ROOT, "test_data", "soc", "mrom.coe"))

for _p in (ELF_PATH, MROM_DAT, MROM_COE):
    _rp = os.path.realpath(_p)
    if _rp != REPO_ROOT and not _rp.startswith(REPO_ROOT + os.sep):
        raise RuntimeError(f"路径越出仓库目录: {_p}")

# BD32 未实现的 CSR：编码落在这里 = BootROM 会踩非法指令 trap
FORBIDDEN_CSR = (0x306,)  # mcounteren（S/U 态访问许可，BD32 无 S/U）


def parse_elf_words(path):
    """最小 ELF32 解析：取所有可加载段（PT_LOAD），按虚拟地址拼接后按字对齐。"""
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"\x7fELF":
        raise ValueError("不是 ELF 文件")
    if data[4] != 1:
        raise ValueError("不是 ELF32")
    (e_entry, e_phoff) = struct.unpack_from("<II", data, 24)
    (e_phentsize, e_phnum) = struct.unpack_from("<HH", data, 42)
    segments = []
    for i in range(e_phnum):
        off = e_phoff + i * e_phentsize
        # ELF32 phdr: p_type p_offset p_vaddr p_paddr p_filesz p_memsz p_flags p_align
        (p_type, p_offset, p_vaddr, _pa, p_filesz, _memsz, _fl, _al) = \
            struct.unpack_from("<IIIIIIII", data, off)
        if p_type == 1 and p_filesz > 0:  # PT_LOAD
            segments.append((p_vaddr, data[p_offset:p_offset + p_filesz]))
    segments.sort()
    # BootROM 段应从 0x0 连续；多段则校验连续后拼接
    blob = b""
    expect = None
    for vaddr, chunk in segments:
        if expect is None:
            expect = vaddr
        elif vaddr != expect:
            raise ValueError(f"段不连续: 期望 0x{expect:X} 实得 0x{vaddr:X}")
        blob += chunk
        expect = vaddr + len(chunk)
    # 防护：切到 ELF 头 = phdr 字段序/偏移解析错误
    if blob[:4] == b"\x7fELF":
        raise ValueError("切进了 ELF 头（PT_LOAD 字段解析错误）")
    words = []
    for i in range(0, len(blob), 4):
        w = blob[i:i + 4].ljust(4, b"\x00")
        words.append("%08x" % int.from_bytes(w, "little"))
    return words


def verify(words):
    if not words:
        raise ValueError("空镜像")
    # 未实现 CSR 的访问检查（访问未实现 CSR 会触发非法指令 trap 死循环）
    for i, w in enumerate(words):
        code = int(w, 16)
        if (code & 0x7F) in (0x73, 0x77):  # SYSTEM opcode（CSR 指令）
            csr = (code >> 20) & 0xFFF
            if csr in FORBIDDEN_CSR:
                raise ValueError(f"word[{i}] 访问已移除 CSR 0x{csr:03X}: {w}")
    # 跳转重定位是否解析由构建 bat 的 objdump 符号注解检查保证


def write_outputs(words):
    with open(MROM_DAT, "w") as f:
        f.write("\n".join(words) + "\n")
    coe = ("memory_initialization_radix=16;\nmemory_initialization_vector=\n"
           + "\n".join(words) + ";")
    with open(MROM_COE, "w") as f:
        f.write(coe)
    print(f"mrom.dat / mrom.coe 已更新: {len(words)} 字")


BUILD_BAT = r"""@echo off
rem BD32 BootROM build (FULL link: call's auipc+jalr reloc needs ld; never use bare as)
rem Generated by update_mrom.py --emit-bat  (ASCII only: cmd reads bat in ANSI/GBK)
set GCC=D:\IC_Design_Toolkit\xpack-riscv-none-elf-gcc-15.2.0-1\bin\riscv-none-elf-gcc.exe
set OBJDUMP=D:\IC_Design_Toolkit\xpack-riscv-none-elf-gcc-15.2.0-1\bin\riscv-none-elf-objdump.exe
set OUTDIR=%~dp0..\..\test_data\soc\mrom_build
set SRC=%~dp0..\..\test_data\soc\mrom.s
if not exist "%OUTDIR%" mkdir "%OUTDIR%"
%GCC% -nostdlib -nostartfiles -march=rv32im_zicsr -mabi=ilp32 -Wl,-Ttext=0x0 -Wl,-e,_start "%SRC%" -o "%OUTDIR%\mrom.elf"
if errorlevel 1 goto :err
%OBJDUMP% -d "%OUTDIR%\mrom.elf" > "%OUTDIR%\mrom.dis"
rem unresolved call shows up as jalr WITHOUT a symbol annotation <...>
for /f "tokens=*" %%L in ('findstr /C:"jalr" "%OUTDIR%\mrom.dis"') do (
    echo %%L | findstr /C:"<" >nul || (echo UNRESOLVED JUMP: %%L & exit /b 1)
)
echo BUILD OK: %OUTDIR%\mrom.elf
goto :eof
:err
echo BUILD FAILED & exit /b 1
"""

SYNTH_BAT = r"""@echo off
rem mrom BRAM IP COE refresh + full synthesis (generated by update_mrom.py --emit-bat)
rem CRITICAL: Vivado cannot see COE content changes; must reset_target
rem + generate_target + re-run mrom_synth_1
D:\Xilinx\Vivado\2023.1\bin\vivado.bat -mode batch -source "%~dp0..\BD32_SoC\synth_flow_mrom_coe.tcl"
"""

SYNTH_TCL_CONTENT = """# update_mrom.py 生成：强制 mrom IP 重读 COE → IP OOC 综合 → 综合 → 实现 → 比特流
open_project D:/Desktop/OpenClaw_Workspace/RISCV_CPU/Working/BD32_SoC/BD32_SoC.xpr
set mrom_xci [get_files -filter {NAME =~ *mrom.xci}]
reset_target all $mrom_xci
generate_target -force all $mrom_xci
reset_run mrom_synth_1
launch_runs mrom_synth_1 -jobs 4
wait_on_run mrom_synth_1
if {[get_property PROGRESS [get_runs mrom_synth_1]] != "100%"} { puts "MROM_OOC_FAILED"; exit 1 }
reset_run synth_1
launch_runs synth_1 -jobs 4
wait_on_run synth_1
if {[get_property PROGRESS [get_runs synth_1]] != "100%"} { puts "SYNTH_FAILED"; exit 1 }
reset_run impl_1
launch_runs impl_1 -to_step write_bitstream -jobs 4
wait_on_run impl_1
if {[get_property PROGRESS [get_runs impl_1]] != "100%"} { puts "IMPL_FAILED"; exit 1 }
report_timing_summary -file [get_property OUTPUT_DIRECTORY [get_runs impl_1]]/timing.rpt
puts "VIVADO_MROM_COE_DONE"
"""


def emit_bat():
    with open(os.path.join(_TOOLS, "update_mrom_build.bat"), "w") as f:
        f.write(BUILD_BAT)
    with open(os.path.join(_TOOLS, "update_mrom_synth.bat"), "w") as f:
        f.write(SYNTH_BAT)
    print("已生成: update_mrom_build.bat, update_mrom_synth.bat")


def emit_tcl():
    tcl = os.path.realpath(os.path.join(REPO_ROOT, "BD32_SoC", "synth_flow_mrom_coe.tcl"))
    os.makedirs(os.path.dirname(tcl), exist_ok=True)
    with open(tcl, "w") as f:
        f.write(SYNTH_TCL_CONTENT)
    print("已生成: BD32_SoC/synth_flow_mrom_coe.tcl")


def main():
    ap = argparse.ArgumentParser(description="BD32 BootROM 校验/生成器（零进程调用）")
    ap.add_argument("--emit-bat", action="store_true", help="生成构建/综合 bat")
    ap.add_argument("--emit-tcl", action="store_true", help="生成 Vivado IP 刷新 tcl")
    ap.add_argument("--check-dat", action="store_true", help="只校验既有 mrom.dat")
    args = ap.parse_args()

    if args.emit_bat:
        emit_bat()
    if args.emit_tcl:
        emit_tcl()
    if args.emit_bat or args.emit_tcl:
        return

    if args.check_dat:
        words = [w.strip() for w in open(MROM_DAT) if w.strip()]
    else:
        if not os.path.exists(ELF_PATH):
            print("未找到 ELF。先运行 update_mrom_build.bat（或 --emit-bat 生成它）",
                  file=sys.stderr)
            sys.exit(1)
        words = parse_elf_words(ELF_PATH)
        verify(words)
        write_outputs(words)
    n306 = sum(1 for w in words if (int(w, 16) >> 20) in FORBIDDEN_CSR)
    print(f"校验通过: {len(words)} 字, 已移除 CSR 引用 {n306}（须为 0）")


if __name__ == "__main__":
    main()
